using Azure;
using Azure.Storage.Blobs;
using Azure.Storage.Blobs.Models;

namespace MediDropProject.Services;

// Both containers stay private. Medication pictures are served through our own read-only endpoint.
public sealed class BlobFileStorage(BlobServiceClient service)
{
    public const string MedicationContainer = "medication-images";
    public const string DocumentContainer = "provider-documents";

    public async Task<string> UploadAsync(string containerName, IFormFile file,
        string extension, string contentType, CancellationToken cancellationToken = default)
    {
        var container = service.GetBlobContainerClient(containerName);
        await container.CreateIfNotExistsAsync(PublicAccessType.None, cancellationToken: cancellationToken);

        var key = $"{Guid.NewGuid():N}.{extension.TrimStart('.')}";
        var blob = container.GetBlobClient(key);
        await using var input = file.OpenReadStream();
        await blob.UploadAsync(input, new BlobUploadOptions
        {
            HttpHeaders = new BlobHttpHeaders { ContentType = contentType }
        }, cancellationToken);
        return key;
    }

    public async Task<Stream?> OpenReadAsync(string containerName, string key,
        CancellationToken cancellationToken = default)
    {
        // Keys are generated by our server, but validate before using them anyway.
        if (string.IsNullOrWhiteSpace(key) || key != Path.GetFileName(key) ||
            key.Contains('/') || key.Contains('\\')) return null;

        try
        {
            var blob = service.GetBlobContainerClient(containerName).GetBlobClient(key);
            var download = await blob.DownloadStreamingAsync(cancellationToken: cancellationToken);
            return download.Value.Content;
        }
        catch (RequestFailedException e) when (e.Status == 404)
        {
            return null;
        }
    }

    public async Task DeleteIfExistsAsync(string containerName, string key)
    {
        await service.GetBlobContainerClient(containerName)
            .GetBlobClient(key).DeleteIfExistsAsync();
    }
}
